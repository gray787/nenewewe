    private static final int PAGE_SIZE = 10;

    public SpellbookScreen() { super(Component.literal("Wizarding Spellbook")); }

    @Override protected void init() {
        clearWidgets();
        int start = page * PAGE_SIZE;
        int left = Math.max(12, width / 2 - 190);
        for (int row = 0; row < PAGE_SIZE && start + row < NAMES.length; row++) {
            final int spellNumber = start + row + 1;
            int y = 48 + row * 25;
            addRenderableWidget(Button.builder(Component.literal(spellNumber + ". " + NAMES[spellNumber - 1]),
                    button -> selectSpell(spellNumber)).bounds(left, y, 190, 20).build());
        }
        addRenderableWidget(Button.builder(Component.literal("Previous"), b -> { page = Math.max(0, page - 1); init(); })
                .bounds(width / 2 - 150, height - 34, 90, 20).build());
        addRenderableWidget(Button.builder(Component.literal("Next"), b -> { page = Math.min((NAMES.length - 1) / PAGE_SIZE, page + 1); init(); })
                .bounds(width / 2 + 60, height - 34, 90, 20).build());
        addRenderableWidget(Button.builder(Component.literal("Close"), b -> onClose())
                .bounds(width / 2 - 45, height - 34, 90, 20).build());
    }

    private void selectSpell(int number) {
        if (Minecraft.getInstance().player != null) {
            Minecraft.getInstance().player.connection.sendCommand("harrypotter spell " + number);
        }
        onClose();
    }

    @Override public void extractRenderState(GuiGraphicsExtractor graphics, int mouseX, int mouseY, float delta) {
        super.extractRenderState(graphics, mouseX, mouseY, delta);
        graphics.centeredText(font, Component.literal("WIZARDING SPELLBOOK"), width / 2, 18, 0xFFFFD875);
        graphics.centeredText(font, Component.literal("Choose a spell to select it. Then right-click with a wand to cast."), width / 2, 32, 0xFFFFFFFF);
        int start = page * PAGE_SIZE;
        for (int row = 0; row < PAGE_SIZE && start + row < NAMES.length; row++) {
            int index = start + row;
            graphics.text(font, DESCRIPTIONS[index], Math.max(210, width / 2 + 8), 54 + row * 25, 0xFFCCCCCC, true);
        }
        graphics.centeredText(font, Component.literal("Page " + (page + 1) + " / " + ((NAMES.length + PAGE_SIZE - 1) / PAGE_SIZE)), width / 2, height - 48, 0xFFFFFFFF);
    }

    @Override public boolean isPauseScreen() { return false; }
